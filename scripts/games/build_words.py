"""Build the word lists for /games (src/app/games/data/{ru,en}.ts).

Sources (download them first, then pass the local paths):
  ru nouns      https://raw.githubusercontent.com/Harrix/Russian-Nouns/main/dist/russian_nouns.txt (MIT, Anton Sergienko)
  ru frequency  https://raw.githubusercontent.com/hermitdave/FrequencyWords/master/content/2018/ru/ru_50k.txt
  en allowed    https://raw.githubusercontent.com/tabatkins/wordle-list/main/words (MIT, Tab Atkins Jr.)
  en answers    https://gist.githubusercontent.com/cfreshman/a03ef2cba789d8cf00c08f767e0fad7b/raw/wordle-answers-alphabetical.txt

Russian guesses are every 5-letter noun of the dictionary (ё folded into е).
Russian answers are the nouns that show up in the frequency list, minus the
EXCLUDE list (names, word forms that are really verbs/adjectives/adverbs,
rude or touchy words), plus the EXTRA everyday nouns (also accepted as
guesses, since the noun list misses a few of them).

  python3 scripts/games/build_words.py RU_NOUNS RU_FREQ EN_ALLOWED EN_ANSWERS
"""

import re
import sys
from pathlib import Path

LENGTH = 5
OUT = Path(__file__).resolve().parents[2] / "src" / "app" / "games" / "data"

EXCLUDE = set("""
через никто знать перед плохо вчера стать парня детка мадам идиот черта месье новое ничто супер дурак погиб
шлюха браво аминь донна пенни пацан разок сорок берет диана полон дрянь целое тварь общее еврей пусто надел
пенис марго ворот макса малый перси аборт риска кайла дебил выпал денек девка сбора полом внука ночка синяя
майер дикая задел фюрер гранд киска девон мышей каппа мразь башка флинт немец кварк тигра облом отсос малик
попка телик стояк кореш финна цыган кольт селин рвота душка резня патер бордо макси отпад чужое понос часок
малец сосок умора чужая манер телка опиум турок раджа ротик поляк ощупь форте брасс чудик ислам сирен матка
сезам френч брика круть алкаш видок запор макао пойло пепси донья жучка фетиш побои орала пайка карга гросс
копал азиат маман залом пещер былое телок хинди засос гнида яичко приор немая евнух милка оргия немка гашиш
иврит колет ларго хаджи рожон мойра мужик
""".split())

EXTRA = set("""
аллея астра багет батон бисер бубен весло влага вьюга гамак гиена грива икона кефир корка лиана мачта мойка
нитка норка овраг пенал рамка слива стопа сушка финик цапля штора ягода ласка дупло совок вафля халва
булка крупа пудра панда коала лемур тапир бизон сазан филин дрозд фазан кулик стриж хорек выдра степь речка
смерч буран пурга стужа кварц печка ширма веник тазик блуза парта мелок пятка челка редис укроп баржа санки
рифма басня эскиз шайба атлет мячик жокей егерь гонец обруч тумба фляга бирка лейка марля скоба шуруп
гайка шалаш хутор пешка ферзь ладья гусли кубок омлет сырок ручей вагон
""".split())


def words(path, encoding="utf-8"):
    for line in Path(path).read_text(encoding=encoding).splitlines():
        if line.strip():
            yield line.split()[0].strip().lower().replace("ё", "е")


def emit(lang, answers, allowed, note):
    extra = sorted(set(allowed) - set(answers))
    body = (
        f"// Generated by scripts/games/build_words.py — do not edit by hand.\n"
        f"// {note}\n\n"
        f"/** Words that can be the hidden word ({len(answers)}). */\n"
        f'export const ANSWERS = "{" ".join(sorted(answers))}";\n\n'
        f"/** Further words accepted as guesses ({len(extra)}). */\n"
        f'export const EXTRA = "{" ".join(extra)}";\n'
    )
    (OUT / f"{lang}.ts").write_text(body, encoding="utf-8")
    print(lang, len(answers), "answers,", len(extra), "extra guesses")


def main(ru_nouns, ru_freq, en_allowed, en_answers):
    OUT.mkdir(parents=True, exist_ok=True)

    ru_word = re.compile(rf"[а-я]{{{LENGTH}}}")
    nouns = {w for w in words(ru_nouns) if ru_word.fullmatch(w)}
    frequent = {w for w in words(ru_freq) if w in nouns}
    bad = sorted(w for w in EXTRA if not ru_word.fullmatch(w))
    if bad:
        sys.exit(f"EXTRA words of the wrong shape: {' '.join(bad)}")
    ru_answers = (frequent - EXCLUDE) | EXTRA
    emit("ru", ru_answers, nouns | EXTRA, "Russian nouns: Harrix/Russian-Nouns (MIT), picked by hermitdave/FrequencyWords.")

    en_word = re.compile(rf"[a-z]{{{LENGTH}}}")
    answers = {w for w in words(en_answers) if en_word.fullmatch(w)}
    allowed = {w for w in words(en_allowed) if en_word.fullmatch(w)} | answers
    emit("en", answers, allowed, "English: tabatkins/wordle-list (MIT) and the original Wordle answer list.")


if __name__ == "__main__":
    if len(sys.argv) != 5:
        sys.exit(__doc__)
    main(*sys.argv[1:])
